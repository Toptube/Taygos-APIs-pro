import { boolean, integer, pgTable, text, timestamp } from 'drizzle-orm/pg-core';

export const taygosSettings = pgTable('taygos_settings', {
  id: text('id').primaryKey(),
  adminPasswordHash: text('admin_password_hash'),
  adminOwnerUid: text('admin_owner_uid'),
  vaultMasterKeyHex: text('vault_master_key_hex'),
  vaultSessionKeyHex: text('vault_session_key_hex'),
  strategy: text('strategy').notNull().default('priority_failover'),
  maxRetries: integer('max_retries').notNull().default(5),
  circuitBreakerThreshold: integer('circuit_breaker_threshold').notNull().default(2),
  cooldownSeconds: integer('cooldown_seconds').notNull().default(30),
  roundRobinCursor: integer('round_robin_cursor').notNull().default(0),
  updatedAt: timestamp('updated_at').defaultNow().notNull(),
});

export const taygosKeys = pgTable('taygos_keys', {
  id: text('id').primaryKey(),
  name: text('name').notNull(),
  description: text('description').notNull().default(''),
  publicKey: text('public_key').notNull().unique(),
  secretMasked: text('secret_masked').notNull(),
  secretHash: text('secret_hash').notNull(),
  hmacSealedSecret: text('hmac_sealed_secret').notNull().default(''),
  perpetual: boolean('perpetual').notNull().default(true),
  expiresAt: text('expires_at'),
  scopesJson: text('scopes_json').notNull().default('["gateway:execute","ai:generate"]'),
  requireHmac: boolean('require_hmac').notNull().default(false),
  status: text('status').notNull().default('active'),
  createdAt: text('created_at').notNull(),
  lastUsedAt: text('last_used_at'),
  requestCount: integer('request_count').notNull().default(0),
  failoverCount: integer('failover_count').notNull().default(0),
  updatedAt: timestamp('updated_at').defaultNow().notNull(),
});

export const taygosProviders = pgTable('taygos_providers', {
  id: text('id').primaryKey(),
  slug: text('slug'),
  name: text('name').notNull(),
  category: text('category').notNull().default('llm'),
  specialty: text('specialty'),
  adapter: text('adapter').notNull(),
  baseUrl: text('base_url').notNull(),
  apiKeyUrl: text('api_key_url'),
  model: text('model').notNull(),
  authHeader: text('auth_header').notNull().default('Authorization'),
  apiKeyMasked: text('api_key_masked').notNull().default('not-set'),
  apiKeySealed: text('api_key_sealed').notNull().default(''),
  usesServerEnv: boolean('uses_server_env').notNull().default(false),
  requiresApiKey: boolean('requires_api_key').notNull().default(true),
  freeModelsCount: integer('free_models_count'),
  maxContext: integer('max_context'),
  tagline: text('tagline'),
  verifiedProtocolsJson: text('verified_protocols_json'),
  priority: integer('priority').notNull().default(50),
  weight: integer('weight').notNull().default(50),
  timeoutMs: integer('timeout_ms').notNull().default(18000),
  enabled: boolean('enabled').notNull().default(true),
  health: text('health').notNull().default('needs_key'),
  consecutiveFailures: integer('consecutive_failures').notNull().default(0),
  cooldownUntil: text('cooldown_until'),
  simulatorBehavior: text('simulator_behavior').notNull().default('healthy'),
  totalRequests: integer('total_requests').notNull().default(0),
  successfulRequests: integer('successful_requests').notNull().default(0),
  failedRequests: integer('failed_requests').notNull().default(0),
  avgLatencyMs: integer('avg_latency_ms').notNull().default(0),
  lastError: text('last_error'),
  lastCheckedAt: text('last_checked_at'),
  updatedAt: timestamp('updated_at').defaultNow().notNull(),
});

export const taygosLogs = pgTable('taygos_logs', {
  id: text('id').primaryKey(),
  timestamp: text('timestamp').notNull(),
  entryJson: text('entry_json').notNull(),
  createdAt: timestamp('created_at').defaultNow().notNull(),
});
